//! rubash#2608 — `${!N@op}`: an indirect expansion carrying a
//! transformation operator whose target name is held in a POSITIONAL
//! parameter silently expanded to the empty string.
//!
//! GNU subst.c:7839-7881 parameter_brace_find_indir expands the holder
//! as a parameter reference, so every legal parameter kind can hold the
//! target name (subst.c:7907-7910: "An indirect reference to a
//! positional parameter or a special parameter is ok"), and
//! get_var_and_type (subst.c:8540) names the transform's variable
//! through the same resolution. rubash's transform entry
//! (indirect_parameter_transform) consulted env_vars only, so the
//! holder "1"/"2" never resolved and the whole transform fell through
//! to nothing. This is the defect that made ble.sh's `ble/is-array`
//! (`[[ ${!1@a} == *a* ]]`, niu#805) report every array as a non-array.
//!
//! All expectations below were generated by running the probe scripts
//! through GNU bash 5.3.20 (~/workspace/rubash-audit/gnu-bash-5.3.20)
//! as script files; they are byte-exact stdout plus exit code.

use std::fs;
use std::path::PathBuf;
use std::process::Command;

const RUBASH: &str = env!("CARGO_BIN_EXE_rubash");

fn run_script(tag: &str, script: &str) -> (String, String, Option<i32>) {
    let dir: PathBuf =
        std::env::temp_dir().join(format!("rubash-issue2608-{tag}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("create scratch dir");
    let path = dir.join("probe.sh");
    fs::write(&path, script).expect("write probe script");
    let output = Command::new(RUBASH)
        .arg(&path)
        .output()
        .expect("run rubash");
    let result = (
        String::from_utf8_lossy(&output.stdout).into_owned(),
        String::from_utf8_lossy(&output.stderr).into_owned(),
        output.status.code(),
    );
    let _ = fs::remove_dir_all(&dir);
    result
}

fn assert_gnu(tag: &str, script: &str, expected_stdout: &str) {
    let (stdout, stderr, code) = run_script(tag, script);
    assert_eq!(code, Some(0), "{tag} exit: stderr: {stderr}");
    assert_eq!(stdout, expected_stdout, "{tag} stdout (stderr: {stderr})");
}

#[test]
fn issue_verbatim_three_lines() {
    // The issue's reproducer, verbatim: variable holder (control),
    // positional holder in the ble/is-array shape, positional @Q at $2.
    assert_gnu(
        "verbatim",
        concat!(
            "arr=([0]=\"x\" [8]=\"y\" [13]=\"z\"); arrname=arr\n",
            "echo \"indirect_a=[${!arrname@a}]\"\n",
            "f() { [[ ${!1@a} == *a* ]] && echo \"is-array: YES\" || echo \"is-array: NO\"; }\n",
            "f arr\n",
            "g() { echo \"pos2_Q=[${!2@Q}]\"; }; g zz arr\n",
        ),
        "indirect_a=[a]\nis-array: YES\npos2_Q=['x']\n",
    );
}

#[test]
fn positional_holder_transform_family() {
    // @a/@Q/@A/@k/@U at position 1 (indexed array target) and
    // @a/@A/@k/@K at position 2 (assoc target; @a must report the `A`
    // attribute). GNU outputs generated from the same script file.
    assert_gnu(
        "family",
        concat!(
            "arr=(x y z)\n",
            "declare -A assoc=([k1]=v1)\n",
            "t() {\n",
            "  echo \"p1_a=[${!1@a}]\"\n",
            "  echo \"p1_Q=[${!1@Q}]\"\n",
            "  echo \"p1_A=[${!1@A}]\"\n",
            "  echo \"p1_k=[${!1@k}]\"\n",
            "  echo \"p1_U=[${!1@U}]\"\n",
            "  echo \"p2_a=[${!2@a}]\"\n",
            "  echo \"p2_A=[${!2@A}]\"\n",
            "  echo \"p2_k=[${!2@k}]\"\n",
            "  echo \"p2_K=[${!2@K}]\"\n",
            "}\n",
            "t arr assoc\n",
        ),
        concat!(
            "p1_a=[a]\n",
            "p1_Q=['x']\n",
            "p1_A=[declare -a arr='x']\n",
            "p1_k=['x']\n",
            "p1_U=[X]\n",
            "p2_a=[A]\n",
            "p2_A=[declare -A assoc]\n",
            "p2_k=[]\n",
            "p2_K=[]\n",
        ),
    );
}

#[test]
fn subscript_holder_and_unset_positional() {
    // A `name[sub]` element is a legal holder (the plain path already
    // resolves it); an unset positional holder expands empty, silently
    // (GNU: parameter_brace_find_indir yields NULL and the transform
    // never applies) — it must NOT become a quoted empty `''`.
    assert_gnu(
        "holders",
        concat!(
            "arr=(x y)\n",
            "zz=\"hi there\"\n",
            "holders=(arr zz)\n",
            "echo \"sub0_a=[${!holders[0]@a}]\"\n",
            "echo \"sub1_Q=[${!holders[1]@Q}]\"\n",
            "u() { echo \"unset5_a=[${!5@a}]\"; echo \"unset5_Q=[${!5@Q}]\"; }\n",
            "u arr\n",
        ),
        concat!(
            "sub0_a=[a]\n",
            "sub1_Q=['hi there']\n",
            "unset5_a=[]\n",
            "unset5_Q=[]\n",
        ),
    );
}

#[test]
fn subscript_holder_class_and_error_surface() {
    // The subscripted-holder class beyond literal indices (GNU outputs
    // generated from the same script file): a variable subscript and
    // an arithmetic subscript are evaluated like the plain path
    // evaluates them, an assoc key names the element, and an unset
    // element expands empty silently. The error surface matches too:
    // t for a general subscript is the ELEMENT value, so an element
    // that is not a valid variable name reports
    // `<t>: invalid variable name` under an operator tail (the
    // whole-array join is GNU's t for the `[@]`/`[*]` subscript only).
    assert_gnu(
        "subclass",
        concat!(
            "arr=(x y)\n",
            "zz=\"hi there\"\n",
            "holders=(arr zz)\n",
            "i=1\n",
            "echo \"varsub_Q=[${!holders[$i]@Q}]\"\n",
            "echo \"arithsub_Q=[${!holders[i]@Q}]\"\n",
            "declare -A m=([k]=zz)\n",
            "echo \"assoc_Q=[${!m[k]@Q}]\"\n",
            "echo \"unset9_Q=[${!holders[9]@Q}]\"\n",
        ),
        concat!(
            "varsub_Q=['hi there']\n",
            "arithsub_Q=['hi there']\n",
            "assoc_Q=['hi there']\n",
            "unset9_Q=[]\n",
        ),
    );
    for (tag, script) in [
        (
            "bad-indexed",
            "bad=(\"1bad\" x)\necho \"bad0_Q=[${!bad[0]@Q}]\"\necho \"rc=$?\"\necho \"after\"\n",
        ),
        (
            "bad-default",
            "bad=(\"1bad\" x)\necho \"bad0_def=[${!bad[0]:-d}]\"\necho \"rc=$?\"\necho \"after\"\n",
        ),
        (
            "bad-assoc",
            "declare -A mb=([k]=\"1bad\")\necho \"badk_Q=[${!mb[k]@Q}]\"\necho \"rc=$?\"\necho \"after\"\n",
        ),
    ] {
        let (stdout, stderr, code) = run_script(tag, script);
        assert_eq!(code, Some(0), "{tag} exit: stderr: {stderr}");
        assert_eq!(stdout, "rc=1\nafter\n", "{tag} stdout (stderr: {stderr})");
        assert!(
            stderr.contains("1bad: invalid variable name"),
            "{tag} stderr: {stderr}"
        );
    }
}

#[test]
fn at_arm_source_controls() {
    // The [@]/[*] arm of the transform entry (source's element values
    // name the target — the rubash#1147 shape) keeps its semantics, and
    // a local variable holder resolves like a global one.
    assert_gnu(
        "at-arm",
        concat!(
            "a=(x)\n",
            "x=\"hi there\"\n",
            "echo \"src_at_Q=[${!a[@]@Q}]\"\n",
            "echo \"src_star_Q=[${!a[*]@Q}]\"\n",
            "arr=(x y z)\n",
            "s=arr\n",
            "echo \"scalar_src_at_Q=[${!s[@]@Q}]\"\n",
            "g() {\n",
            "  local n=arr\n",
            "  echo \"local_holder_a=[${!n@a}]\"\n",
            "  echo \"local_holder_Q=[${!n@Q}]\"\n",
            "}\n",
            "g\n",
            "e=\"\"\n",
            "r=e\n",
            "echo \"set_empty_Q=[${!r@Q}]\"\n",
        ),
        concat!(
            "src_at_Q=['hi there']\n",
            "src_star_Q=['hi there']\n",
            "scalar_src_at_Q=['x']\n",
            "local_holder_a=[a]\n",
            "local_holder_Q=['x']\n",
            "set_empty_Q=['']\n",
        ),
    );
}
